  static final DilServisi instance = DilServisi._();

  static const String _prefKey = 'secili_dil_kodu';

  static const List<DilSecenegi> desteklenenDiller = [
    DilSecenegi(kod: 'tr', ulkeKodu: 'TR', ad: 'Türkçe', bayrak: '🇹🇷'),
    DilSecenegi(kod: 'en', ulkeKodu: 'US', ad: 'English', bayrak: '🇬🇧'),
    DilSecenegi(kod: 'de', ulkeKodu: 'DE', ad: 'Deutsch', bayrak: '🇩🇪'),
    DilSecenegi(kod: 'fr', ulkeKodu: 'FR', ad: 'Français', bayrak: '🇫🇷'),
    DilSecenegi(kod: 'es', ulkeKodu: 'ES', ad: 'Español', bayrak: '🇪🇸'),
    DilSecenegi(kod: 'ru', ulkeKodu: 'RU', ad: 'Русский', bayrak: '🇷🇺'),
  ];

  String _dilKodu = 'tr';
  double _gecisOpakligi = 1.0;

  String get dilKodu => _dilKodu;
  double get gecisOpakligi => _gecisOpakligi;

  Locale get locale {
    final secili = desteklenenDiller.firstWhere(
      (d) => d.kod == _dilKodu,
      orElse: () => desteklenenDiller.first,
    );
    return secili.locale;
  }

  List<Locale> get supportedLocales =>
      desteklenenDiller.map((d) => d.locale).toList();

  Future<void> baslat() async {
    final prefs = await SharedPreferences.getInstance();
    final kayitli = prefs.getString(_prefKey);
    if (kayitli != null && desteklenenDiller.any((d) => d.kod == kayitli)) {
      _dilKodu = kayitli;
    }
  }

  Future<void> dilDegistir(String yeniKod) async {
    if (_dilKodu == yeniKod) return;
    if (!desteklenenDiller.any((d) => d.kod == yeniKod)) return;

    _gecisOpakligi = 0.25;
    notifyListeners();

    await Future.delayed(const Duration(milliseconds: 120));

    _dilKodu = yeniKod;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKey, yeniKod);

    _gecisOpakligi = 1.0;
    notifyListeners();
  }

  String cevir(String anahtar, [Map<String, String>? parametreler]) {
    final dilHaritasi = _sozluk[_dilKodu] ?? _sozluk['tr']!;
    String metin = dilHaritasi[anahtar] ?? _sozluk['tr']![anahtar] ?? anahtar;

    if (parametreler != null) {
      parametreler.forEach((key, value) {
        metin = metin.replaceAll('{$key}', value);
      });
    }
    return metin;
  }

